/* ★ 臂回转（SERVO_YAW，SG90）—— 柱坐标的 θ 轴
 *
 *   朝向角定义（从车头方向量起）：
 *        0°   = 正前方（取块工作位）
 *        90°  = 正左
 *        180° = 正后方（收起位 / 投放位。★ 不要改小）
 *   名义上 s = 朝向角，装舵盘时让 **s = 0° 时爪朝正前方**。
 *   ⚠ 实际舵机角在 arm_cal.h 的 ARM_YAW_DEG_0/90/180 里，下面只是别名。
 *
 *   ★★ 柱坐标下的回转铁律（= 四连杆时代"先抬平再转"的等价物）：
 *        **先把滑座升到最高档（爪尖 95 > 甲板 88.5），再回转。**
 *      爪偏心 52mm，回转时爪会扫过车侧；爪尖最低 64.5，比甲板面还低 24mm。
 *      低位硬转 = 爪插进甲板/储仓 = 扫齿或别断爪架。
 *      arm.c 的序列都按「升最高 → 回转 → 再降到位」写，
 *      Arm_SetYaw() 里另有一道互锁兜底，别绕过它。
 */
#define SERVO_YAW_FRONT      ARM_YAW_DEG_0     /* 朝正前方（工作位） */
#define SERVO_YAW_LEFT       ARM_YAW_DEG_90    /* 朝正左（一般只用做过渡） */
#define SERVO_YAW_STOW       ARM_YAW_DEG_180   /* 朝正后方（收起位）。★ 不要改小 */

/* ============================================================================
 * ★★ 前铲（SERVO_SCOOP，SG90）—— 2026-10-17 按机械组实物重写
 *
 * 【实物是什么】不是"铲"，是**翻转式四齿耙 + 背板**（一种「搂进簸箕」的机构）：
 *       4 根平行齿（齿间有缝，缝和背板上的竖槽对齐）
 *     + 每根齿末端一个横向挡唇
 *     + 一块背板（承托面）
 *     + 装在筒里的 1 个舵机，整个耙绕舵机轴翻转（**只有 1 个自由度**）
 *
 *   齿朝前下方  → 齿尖贴地，能"扫"到地面的块（SCOOP_ANG_GROUND）
 *   齿转向上    → 背板变成托盘，块躺在背板上（SCOOP_ANG_HOLD）
 *   ⇒ 收块的原理**不是楔入**（方块贴着地面，底下零间隙，齿尖插不进去），
 *     而是「**先把块顶/扫到齿前，再快速翻转把它搂到背板上**」。
 *     代码里的动作序列就是按这个原理写的（见 auto_task.c 的 MACRO_GROUND）。
 *
 * 【★ 分工铁律】地面上的方块**全部由前铲负责，机械臂完全不参与**：
 *   柱坐标臂的爪尖最低只到离地 64.5mm，而地面方块顶面才 30mm —— 差 34.5mm，
 *   物理上够不到。反过来，**铲里的块也永远不往储仓送**（铲在车头 x≈+140，
 *   仓在车中 x≈−32~+68，中间隔着 200mm 和整个臂座）。
 *   ⇒ 前铲就是一个**能装 1~3 块的外挂仓**，兜住即算「携带」，不转移。
 *
 * 【★★★ 下面 5 个角度全是「待实测」—— 上电第一件事就是标它们】
 *   舵机装在筒里，舵盘朝哪一侧、齿朝哪边，照片看不出来，只能拨着试。
 *   标定三步（架空车、不装轮子也行，手放旁边随时断电）：
 *     ① 拨到 SCOOP_ANG_GROUND，看齿尖是不是**最低、几乎贴地**；
 *        如果反过来是"齿朝天"，说明**极性反了**，把 5 个数全部换成
 *        `180 − 原值`，再试一次（别改代码逻辑）。
 *     ② 拨到 SCOOP_ANG_HOLD，看背板是不是基本水平（能托住块）。
 *     ③ 拨到 SCOOP_ANG_STOW，量车头到车尾的总长 —— **必须 ≤290**。
 *        ★ 这一条是检录红线：齿长 90~100 的话，只有"竖立"才不超长。
 *
 * 【缝宽决定生死（这是全车最容易被忽略的一个数）】
 *   用卡尺量"齿与齿之间的净缝"，对照 30×30 的方块：
 *     缝 < 26  → 块一定被齿面挡住，翻转时被托上背板      ✅ 最安全
 *     缝 26~34 → 块可能半卡在缝里，翻转时掉不进背板      ⚠ 最危险，靠斜进规避
 *     缝 > 34  → 块直接陷进缝/槽里                        ⚠ 能带住，但倒块困难
 * ==========================================================================*/
#define SCOOP_ANG_GROUND        150     /* 齿尖最低、贴地扫掠（铲翻的起点） */
