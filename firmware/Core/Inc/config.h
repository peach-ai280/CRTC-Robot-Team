/* ★★★ 上电后等多久再开始跟接收器通信（毫秒）
 *
 * 为什么要有这个：PS2 无线接收器上电后要 0.5~1 秒完成内部初始化 + 射频握手。
 * 如果单片机在这之前就开始打 SPI 时钟，接收器会进异常状态 —— 之后无论怎么
 * 轮询它都不回应，表现就是 raw[9] 全是 0xFF，看起来像"线没接好"。
 *
 * 这个值给大一点没坏处（只影响上电慢多久），给太小会踩坑。
 * 现象：raw 全 FF 但接线确认没问题 → 先把这里加到 2000 再试。 */
#define PS2_POWERON_DELAY_MS     1500

/* ★ PS2 时序放宽量（2026-10-18 加）
 *
 * 现象：raw 变成 "00 00 FF FF ..."（前两字节被拉低、后面全 FF），
 *       说明线通了、接收器也在响应，但数据没完整移出来。
 * 原因：兼容接收器的移位速度比原装慢，字节间隔不够就丢后面的字节。
 *
 * 这是两个"只影响速度、不影响正确性"的参数，调大最坏是慢一点。
 *   PS2_BYTE_GAP_US   每发完一个字节后等多久（原 15µs）
 *   PS2_CS_SETUP_US   片选拉低后等多久再打第一个时钟（原 20µs）
 * 如果还能收到数据但不对，可以继续加大到 120 / 80。 */
#define PS2_BYTE_GAP_US          60
#define PS2_CS_SETUP_US          50

/* 摇杆中位死区（0~128）：手柄摇杆回中不一定精确是 128 */
#define PS2_STICK_DEADZONE       12
/* 手柄失联保护：连续这么多次没收到有效数据就停机（SPI 一次轮询 ~10ms） */
#define PS2_LOST_THRESHOLD       25
/* 手柄失联后的动作：0=刹车不动 1=缓慢停车 */
#define PS2_LOST_ACTION          0

/* 摇杆 -> 速度 的映射曲线：1.0=线性，>1=低速更细腻（推荐 1.4） */
