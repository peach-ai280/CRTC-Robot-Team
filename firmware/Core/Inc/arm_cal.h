#ifndef __ARM_CAL_H
#define __ARM_CAL_H

/* ============================================================================
 * arm_cal.h —— ★★ 机械臂标定表（柱坐标构型 / Cylindrical Robot）
 *
 * 【一句话】机械组怎么改尺寸，电控这边**只需要改这一个文件**，其他 .c 一律不动。
 *
 * ---------------------------------------------------------------------------
 * 【1】这个机械臂长什么样（2026-10-10 定稿，别再想成"会摆动的关节臂"）
 *
 *   柱坐标 = 三个**互相独立、互不干涉**的自由度：
 *
 *       ① θ 回转（yaw）  整根立柱绕底座竖直轴转     0°=正前 / 90°=正左 / 180°=正后
 *       ② Z 升降（lift） 滑座沿立柱上下直线滑动      0=最低 / 30.5mm=最高
 *       ③ 夹爪开合（grip）
 *
 *   ★ 三个自由度各自一个舵机、各自一条指令，**没有逆运动学、没有联动**。
 *     所以电控需要的全部信息就两张表：
 *          「我要多高」→「升降舵机转到多少度」     ← ARM_LIFT 表
 *          「我要朝哪」→「回转舵机转到多少度」     ← ARM_YAW 表
 *
 * ---------------------------------------------------------------------------
 * 【2】三个舵机分别接在哪（接线冻结，机械组照这个预留线）
 *
 *       夹爪  SERVO_GRIP  ← PA0  / TIM2_CH1   SG90
 *       升降  SERVO_ARM   ← PA1  / TIM2_CH2   SG90   ★ 语义 = 柱坐标的 Z 轴
 *       回转  SERVO_YAW   ← PA11 / TIM1_CH4   SG90   (TIM2 已满，只能用 TIM1)
 *       前铲  SERVO_SCOOP ← PA2  / TIM2_CH3   SG90   （地面方块用，与臂无关）
 *       探杆  SERVO_EXTRA ← PA3  / TIM2_CH4   SG90   （挑杆/洞窟，与臂无关）
 *
 *   ⚠ 这五个引脚**不能换**（换了要重写初始化 + 定时器 + 中断，等于重做）。
 *     要加第 6 路先找电控 —— 第 1 顺位是 TIM1_CH1 = PA8，但那个脚现在是蜂鸣器。
 *
 * ---------------------------------------------------------------------------
 * 【3】标记约定 —— 看到这两个标记就知道该找谁
 *
 *   [机械]  = 机械侧的设计值/实测值。**机械组改了任何一个，必须通知电控**，
 *             由电控改本文件 → 重新编译 → 重新烧录。机械组不要自己改 .c。
 *   [实测]  = 装完之后要拿尺子 + 串口标出来的数。**现在填的是名义值**，
 *             标定完把整行替换成实测值（见第 6 节标定流程）。
 * ==========================================================================*/

/* ---------------------------------------------------------------------------
 * 4. [机械] 几何参数 —— 只是"账本"，固件不用它们算控制
 *
 *    留在这里的目的：① 机械组改尺寸时有个唯一出处可对照；
 *                    ② 电控算「目标高度 → 该升到几毫米」时要用下面两个端点。
 *    ⚠ 单位一律 mm，原点 = 地面。
 * -------------------------------------------------------------------------*/
#define ARM_GEO_DECK_TOP        88.5f   /* 甲板面离地（已含 4mm 板厚） */
#define ARM_GEO_BASE_H          40.0f   /* 回转底座高 */
#define ARM_GEO_TT_H             6.0f   /* 回转盘厚 */
#define ARM_GEO_MAST_H          62.65f  /* 立柱高（底座顶 134.5 → 柱顶 197.15） */
#define ARM_GEO_MAST_TOP       197.15f  /* 立柱顶（滑座走过 z<197 全是禁区，装配只能从柱顶） */
#define ARM_GEO_CAP_H            6.0f   /* 顶帽厚（升降舵机吊在它下面） */
#define ARM_GEO_CAP_TOP        203.15f  /* 顶帽顶 */
#define ARM_GEO_CAR_H           32.0f   /* 滑座高 */
#define ARM_GEO_CRANK_Z        185.75f  /* 曲柄回转中心离地 = 销中位 137.75 + 连杆 48 */
#define ARM_GEO_LINK_L          48.0f   /* 连杆孔距（恒定，这是柱坐标的"命根子"） */
#define ARM_GEO_CRANK_R         15.25f  /* 曲柄半径 R */
#define ARM_GEO_STROKE          30.5f   /* ★ 全行程 = 2R。滑座底 ∈ [134.5, 165.0] */
#define ARM_GEO_BOOM_L          52.0f   /* 爪偏心（横臂从立柱轴往外伸多远） */
#define ARM_GEO_CLAW_DROP       46.0f   /* 爪架底 → 爪尖 的落差 */
#define ARM_GEO_CLAW_TIP_LO     64.5f   /* ★ lift=0 时爪尖离地（低于甲板 88.5，所以低位不能回转！） */
#define ARM_GEO_CLAW_TIP_HI     95.0f   /* ★ lift=30.5 时爪尖离地（高于甲板 6.5） */
#define ARM_GEO_TOTAL_TOP      204.6f   /* 全车最高点（曲柄外缘），红线 210，余 5.4 */

/* ---------------------------------------------------------------------------
 * 5. ★★ 升降标定表（lift）：滑座高度 mm → 升降舵机角度
 *
 *    【为什么是"表"不是"公式"】曲柄滑块的高度和转角是非线性关系
 *    （z = CRANK_Z + R·sinφ − √(L² − (R·cosφ)²)），而且**装配时舵盘怎么对，
 *     只有装完才知道**。所以固件里做成 6 点分段线性插值表：
 *     机械组把立柱/曲柄/行程改成什么样都不影响，只要重新标这 6 个数。
 *
 *    [实测] 下面 6 组是**名义值**：假设「装舵盘时把 s=90° 对到曲柄水平(φ=0)」，
 *           按设计行程 30.5mm 等分算出来的。**装完必须实测替换**。
 *
 *    标定方法（见 test_arm 固件的手动模式）：
 *      ① 串口发 "0" 让滑座走到最低 → 记下舵机角 → 填 ARM_LIFT_DEG_0
 *      ② 每隔约 6mm 打一个点，一共 6 个点 → 填满 DEG_1..DEG_5
 *      ③ 若某档"到不了"，说明行程不止 30.5，把 ARM_LIFT_MM_x 也一起改。
 * -------------------------------------------------------------------------*/
#define ARM_LIFT_N                 6      /* 采样点数，改了要同步下面两组宏 */

/* 【口径】这里量的是「**爪尖离地高度** mm」—— 装完之后拿尺子从地面量到爪尖。
 *   最直观，也正好是判断"够不够得着某个高度的块"的那个量。
 *   名义值 = 64.5 + (0 / 6.1 / 12.2 / 18.3 / 24.4 / 30.5)，
 *   其中 64.5 = ARM_GEO_CLAW_TIP_LO（滑座在最低位时的爪尖离地）。 */
#define ARM_CAL_TIP_0           64.5f
#define ARM_CAL_TIP_1           70.6f
#define ARM_CAL_TIP_2           76.7f
#define ARM_CAL_TIP_3           82.8f
#define ARM_CAL_TIP_4           88.9f
#define ARM_CAL_TIP_5           95.0f     /* = ARM_GEO_CLAW_TIP_HI */

/* [实测] 名义舵机角（度）。两端的 5/175 是留给舵机的余量，别直接写 0/180（会顶限位吱吱响） */
#define ARM_CAL_DEG_0             5.0f
#define ARM_CAL_DEG_1            47.0f
#define ARM_CAL_DEG_2            70.0f
#define ARM_CAL_DEG_3            92.0f
#define ARM_CAL_DEG_4           118.0f
#define ARM_CAL_DEG_5           175.0f

/* 舵机硬限位（保险丝）：任何情况下都不许把升降舵机开到这两个角度之外 */
#define ARM_LIFT_DEG_MIN          0.0f
#define ARM_LIFT_DEG_MAX        180.0f

/* ---------------------------------------------------------------------------
 * 6. 回转标定表（yaw）：朝向角 → 回转舵机角度
 *
 *    [实测] 名义：s = yaw（装舵盘时把 s=0° 对到爪朝正前方）。
 *           个别舵机顶到 180° 会轻微吱吱响（不烫就没事），响就把 _180 收到 176~178。
 *           ⚠ 改 _180 之后**必须重新量一遍**：爪在收起位还落不落得进储仓最后一列。
 * -------------------------------------------------------------------------*/
#define ARM_YAW_DEG_0             3.0f    /* 爪朝正前（工作位） */
#define ARM_YAW_DEG_90           90.0f    /* 爪朝正左（过渡） */
#define ARM_YAW_DEG_180         177.0f    /* 爪朝正后（收起位 / 投放位）★ 不要改小到 160 以下 */

/* ★★ 互锁（安全底线，别删）：
 *   爪的偏心是 52mm。回转时爪尖会扫过车侧 —— 而爪尖最低能到 64.5，比甲板面 88.5 还低。
 *   所以规定：**yaw 落在下面这个扇区里时，升降不许低于 ARM_LIFT_MM_SAFE**。
 *   否则爪会插进甲板 / 储仓，轻则扫齿，重则把爪架别断。
 *   实现见 arm.c 的 Arm_SetYaw()：检测到危险组合会「先抬到安全高度，本次不转」。 */
#define ARM_YAW_SECTOR_LO        60.0f    /* 危险扇区下界（度） */
#define ARM_YAW_SECTOR_HI       120.0f    /* 危险扇区上界（度） */
#define ARM_TIP_SAFE            89.0f     /* 安全爪尖高度（> 甲板 88.5）。比最高档只低 6mm */

/* ---------------------------------------------------------------------------
 * 7. 目标姿态（比赛口径）
 *
 *    上面 ARM_TGT_* 是场地手册给的"块的高度区间"（离车底板 mm），只作参考。
 *    下面 ARM_TIP_* 才是固件真正用的：**直接写"爪尖要升到离地多少 mm"**，
 *    动作逻辑只写"够到哪个目标"，舵机角由标定表算出来（Arm_SetLift）。
 *
 *    ★ 物资架黄块（离地 250）与地面方块（0~30）**柱坐标臂都够不到**：
 *        物资架 差 155mm  →  用挑杆 SERVO_EXTRA（16_rack_hook 件）
 *        地面块 差 64.5mm →  用前铲 SERVO_SCOOP
 *      这两个不算"臂的目标"，别往下面加。
 * -------------------------------------------------------------------------*/
#define ARM_TGT_FOCUS_LO        70.0f     /* 焦点黄块 底（离车底板） */
#define ARM_TGT_FOCUS_HI       100.0f     /* 焦点黄块 顶 */
#define ARM_TGT_PLAT_LO         72.5f     /* 中央高台面白块 底 */
#define ARM_TGT_PLAT_HI        102.5f
#define ARM_TGT_STEP_LO         87.5f     /* 台阶面白块 底（★ 只够下半截） */
#define ARM_TGT_STEP_HI        117.5f
#define ARM_TGT_CABIN_BOT       94.5f     /* 储仓底（投放落点，爪尖 95.0 → 落差 0.5mm） */

/* ---- ★ 各姿态的升降目标：爪尖离地高度 mm（改动作只改这几个数） ---- */
#define ARM_TIP_HOME            95.0f     /* 收起 / 检录 / 回转安全高度（= 最高档） */
#define ARM_TIP_DROP            95.0f     /* 投放（爪尖 95 落在储仓停车格正上方） */
#define ARM_TIP_FOCUS           85.0f     /* 焦点黄块（70~100 取中） */
#define ARM_TIP_PLATFORM        87.5f     /* 高台面白块（72.5~102.5 取中） */
#define ARM_TIP_STEP            95.0f     /* 台阶面白块（只够下半截，给最高） */

#endif /* __ARM_CAL_H */
