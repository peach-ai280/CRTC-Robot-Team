/* ============================================================================
 * params.cpp —— 默认参数表
 *
 * ⚠ 这里的每一个数都和 firmware/Core/Inc/config.h 一一对应。
 *   如果你在 config.h 里改了参数，这里也要同步改，否则 C 版和 C++ 版
 *   行为会不一致，调试时会出现"同一个动作两套表现"的怪事。
 *
 * 为什么写成 extern const 而不是类内默认值：
 *   类内默认值（NSDMI）会让类变成"非平凡构造"，全局对象就得靠 .init_array
 *   构造函数初始化，而我们的启动文件不跑 .init_array。写成常量表直接进
 *   .rodata，零成本。
 * ==========================================================================*/

